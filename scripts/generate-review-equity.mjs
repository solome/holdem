/** Run with: node scripts/generate-review-equity.mjs */
import { writeFile } from "node:fs/promises";
import { calculateReviewEquity, REVIEW_EQUITY_DEALS } from "../src/review-equity.mjs";

const result = {};
for (const [caseId, deal] of Object.entries(REVIEW_EQUITY_DEALS)) {
  result[caseId] = {};
  for (const [street, size] of [["preflop", 0], ["flop", 3], ["turn", 4], ["river", 5]]) {
    const started = performance.now();
    const outcome = calculateReviewEquity({ ...deal, board: deal.board.slice(0, size) });
    result[caseId][street] = outcome;
    console.log(`${caseId}/${street}: ${outcome.totalOutcomes.toLocaleString("en-US")} exact runouts (${((performance.now() - started) / 1000).toFixed(2)}s)`);
    console.log(outcome.players.map(({ id, equity }) => `${id} ${(equity * 100).toFixed(4)}%`).join(" · "));
  }
}
const source = `// Generated by node scripts/generate-review-equity.mjs; do not edit probabilities by hand.\n// Complete, equally weighted combinations from cards unseen at each street.\n// Every supplied hole card is excluded for every pot. Equity includes split-pot shares.\nexport const REVIEW_EQUITY = ${JSON.stringify(result, null, 2)};\n`;
await writeFile(new URL("../src/review-equity-data.mjs", import.meta.url), source);
